#!/bin/bash

# This script was made to simplify the process of chrooting into a new environment without manually typing the required commands to mount the virtual filesystems!
# It's especially useful when you have to chroot into a new environment multiple times, as it saves time and effort!
# For example, say you're installing Gentoo Linux from another Linux distribution (Fun fact: That's how I installed it!), and you have to chroot into the new environment multiple times to install packages,
# configure the system, bla bla bla. This script will save you time and effort by automating the process of mounting the virtual filesystems and copying over the necessary files!
# Note that the script expects the target filesystem to be mounted at /mnt, and that the script is run with root privileges.
# The script will mount the following:
# /dev
# /proc
# /sys
# /run
# The script will also copy over the following:
# /etc/resolv.conf

# Usage: sudo/doas simpleroot (or just simpleroot if you are already root, check by typing "whoami" in the terminal)

# This part over here checks if the script is being run with root privileges.
if [ "$EUID" -ne 0 ]; then
  echo "Please run this script as root! :("
  exit 1
fi

# Check if a partition is actually mounted at /mnt
if ! mountpoint -q /mnt; then
  echo "Nothing is mounted at /mnt!"
  echo "Please mount your target filesystem to /mnt before running this script. :("
  exit 1
fi

# A helper function to umount the filesystems when the user exits the chroot environment
unmount_filesystems() {
  echo -e "\nUnmounting the virtual filesystems"
  umount -R /mnt/dev 2>/dev/null
  umount -R /mnt/proc 2>/dev/null
  umount -R /mnt/sys 2>/dev/null
  umount -R /mnt/run 2>/dev/null
  echo "Unmounting complete :)"
}

# Trap exit to make sure the function runs even if things don't go as planned
trap unmount_filesystems EXIT

# Create the directories to mount the virtual filesystems if they don't already exist
echo "Creating the directories to mount the virtual filesystems"
mkdir -p /mnt/dev /mnt/proc /mnt/sys /mnt/run
echo -e "Directories created :)\n"

echo "Mounting the virtual filesystems"
mount --type proc /proc /mnt/proc 
mount --rbind /sys /mnt/sys 
mount --make-rslave /mnt/sys 
mount --rbind /run /mnt/run 
mount --make-slave /mnt/run
mount --rbind /dev /mnt/dev 
mount --make-rslave /mnt/dev
echo -e "Mounting complete :)\n"

echo "Copying over /etc/resolv.conf to the new environment"
cp --dereference /etc/resolv.conf /mnt/etc/
echo -e "Copying complete :)\n"

echo "Chrooting into the new environment"
chroot /mnt /bin/bash --rcfile <(echo 'PS1="(chroot) \u@\h:\w# "')

