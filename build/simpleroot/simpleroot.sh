#!/bin/bash
set -u

# This script was made to simplify the process of chrooting into a new environment without manually typing the required commands to mount the virtual filesystems!
# It's especially useful when you have to chroot into a new environment multiple times, as it saves time and effort!
# For example, say you're installing Gentoo Linux from another Linux distribution (Fun fact: That's how I installed it!), and you have to chroot into the new environment multiple times to install packages,
# configure the system, bla bla bla. This script will save you time and effort by automating the process of mounting the virtual filesystems and copying over the necessary files!
# Note that you will have to enter your target mount point (if not it just defaults to /mnt), and that the script is run with root privileges.
# The script will mount the following:
# /dev
# /proc
# /sys
# /run
# The script will also copy over the following:
# /etc/resolv.conf

# Usage: sudo/doas simpleroot (or just simpleroot if you are already root, check by typing "whoami" in the terminal)

# This part over here checks if the script is being run with root privileges.
if [ "$EUID" -ne 0 ]; then
  echo "Please run this script as root! :("
  exit 1
fi

# Ask the user where the target filesystem is mounted
read -p "Where is your target filesystem mounted? (default is /mnt): " TARGET_MOUNTPOINT
TARGET_MOUNTPOINT=${TARGET_MOUNTPOINT:-/mnt} # Set default value to /mnt if the user doesn't provide one

# Strip any trailing slashes (even multiple ones like /mnt//)
while [[ "$TARGET_MOUNTPOINT" != "/" && "$TARGET_MOUNTPOINT" == */ ]]; do
  TARGET_MOUNTPOINT=${TARGET_MOUNTPOINT%/}
done

# Immediately reject the live root filesystem and exit
if [ "$TARGET_MOUNTPOINT" == "/" ]; then
  echo "Target is absolutely NOT going to be your root filesystem! Enter an actual mount point or don't use this script! >:("
  exit 1
fi


# Check if a partition is actually mounted at the target mount point
if ! mountpoint -q "$TARGET_MOUNTPOINT"; then
  echo "Nothing is mounted at $TARGET_MOUNTPOINT!"
  echo "Please mount your target filesystem to $TARGET_MOUNTPOINT before running this script. :("
  exit 1
fi

# A helper function to umount the filesystems when the user exits the chroot environment
unmount_filesystems() {
  echo -e "\nUnmounting the virtual filesystems"
  umount -R "$TARGET_MOUNTPOINT/run" 2>/dev/null
  umount -R "$TARGET_MOUNTPOINT/dev" 2>/dev/null
  umount -R "$TARGET_MOUNTPOINT/sys" 2>/dev/null
  umount -R "$TARGET_MOUNTPOINT/proc" 2>/dev/null
  echo "Unmounting complete :)"
}

# Trap exit to make sure the function runs even if things don't go as planned
trap unmount_filesystems EXIT

# Check if any mounting failed
check_mounting() {
  local label="$1"
  shift
  if ! "$@"; then
    echo "Failed to mount $label! Exiting before chroot. :("
    exit 1
  fi
}

# Create the directories to mount the virtual filesystems if they don't already exist
echo "Creating the directories to mount the virtual filesystems"
mkdir -p "$TARGET_MOUNTPOINT/dev" "$TARGET_MOUNTPOINT/proc" "$TARGET_MOUNTPOINT/sys" "$TARGET_MOUNTPOINT/run" "$TARGET_MOUNTPOINT/etc"
echo -e "Directories created :)\n"

# Mount the virtual filesystems
echo "Mounting the virtual filesystems"
check_mounting "proc" mount --type proc /proc "$TARGET_MOUNTPOINT/proc"
check_mounting "sys (rbind)" mount --rbind /sys "$TARGET_MOUNTPOINT/sys"
check_mounting "sys (rslave)" mount --make-rslave "$TARGET_MOUNTPOINT/sys"
check_mounting "dev (rbind)" mount --rbind /dev "$TARGET_MOUNTPOINT/dev"
check_mounting "dev (rslave)" mount --make-rslave "$TARGET_MOUNTPOINT/dev"
check_mounting "run (rbind)" mount --rbind /run "$TARGET_MOUNTPOINT/run"
check_mounting "run (rslave)" mount --make-rslave "$TARGET_MOUNTPOINT/run"
echo -e "Mounting complete :)\n"

# Copy over /etc/resolv.conf to the new environment
echo "Copying over /etc/resolv.conf to the new environment"
if [ -e /etc/resolv.conf ]; then
  cp --dereference /etc/resolv.conf "$TARGET_MOUNTPOINT/etc/resolv.conf"
fi
echo -e "Copying complete :)\n"

# Now chroot into the new environment!
echo "Chrooting into the new environment"
chroot "$TARGET_MOUNTPOINT" /bin/bash --rcfile <(echo 'PS1="(chroot) \u@\h:\w# "')

